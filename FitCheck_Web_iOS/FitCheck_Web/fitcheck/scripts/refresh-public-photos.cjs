/* global __dirname */
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
try {
  execFileSync('python3', [path.join(__dirname, 'normalize-public-photos.py'), path.join(root, 'public/item-photos')], { stdio: 'inherit' });
} catch {
  console.error('Photo conversion failed. Use Python 3 with Pillow installed (python3 -m pip install --upgrade pillow).');
  process.exit(1);
}
const names = fs.readdirSync(path.join(root, 'public/item-photos'))
  .filter((name) => /\.(png|jpe?g|webp|gif)$/i.test(name)).sort();
const entries = names.map((name) => `    { name: ${JSON.stringify(name)}, source: require(${JSON.stringify('./public/item-photos/' + name)}) },`);
fs.writeFileSync(path.join(root, 'publicPhotos.js'),
  '// Generated by npm run photos:refresh. Static imports also bundle these images for iOS.\n' +
  'export const PUBLIC_PHOTOS = [\n' + entries.join('\n') + '\n];\n\n' +
  'export function publicPhotoUri(name) {\n    return `public-photo:${name}`;\n}\n\n' +
  'export function itemImageSource(uri) {\n' +
  '    if (uri?.startsWith("public-photo:")) {\n' +
  '        return PUBLIC_PHOTOS.find((photo) => photo.name === uri.slice(13))?.source;\n' +
  '    }\n    return { uri };\n}\n');
console.log(`Registered ${names.length} public photos.`);
